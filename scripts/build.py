RTL_ATTR = ' lang="fa" dir="rtl"'
FA_DIGITS = str.maketrans("0123456789", "۰۱۲۳۴۵۶۷۸۹")


def rtl_attr(text: str) -> str:
    """The Persian attributes for a piece of text written in Persian (e.g. a lab title on an English page)."""
    return RTL_ATTR if re.search(r"[\u0600-\u06FF]", text) else ""


def num(n, lang: str) -> str:
    return str(n).translate(FA_DIGITS) if lang == "fa" else str(n)


def pages_label(ref: str, lang: str) -> str:
    """'pp. 3–9' → 'صص. ۳–۹' in a Persian lesson (page numbers read right to left like the text)."""
    if lang != "fa":
        return ref
    ref = re.sub(r"\bpp\.\s*", "صص. ", ref)
    ref = re.sub(r"\bp\.\s*", "ص. ", ref)
    return ref.replace(";", "؛").replace(",", "،").translate(FA_DIGITS)


# In right-to-left text, punctuation between two Latin words joins them into one left-to-right run,
# which then reads in the wrong order ("A، B، C" shows as C، B، A). A right-to-left mark after the
# punctuation keeps each Latin word its own run.
RLM_AFTER = re.compile(r"([،؛؟!:.])(?= )")


# ---------------------------------------------------------------- front matter

FM_RE = re.compile(r"\A---\n(.*?)\n---\n", re.S)


def split_front_matter(text: str) -> tuple[dict, str]:
    m = FM_RE.match(text)
    if not m:
        return {}, text
    meta = {}
    for line in m.group(1).splitlines():
        if ":" not in line or line.startswith((" ", "#")):
            continue
        key, _, raw = line.partition(":")
        meta[key.strip()] = parse_scalar(raw.strip())
    return meta, text[m.end():]


def parse_scalar(raw: str):
    if raw in ("", "null", "~"):
        return None
    if raw.startswith("["):
        try:
            return json.loads(raw)
        except ValueError:
            return [x.strip().strip("\"'") for x in raw.strip("[]").split(",") if x.strip()]
    if raw.startswith('"') and raw.endswith('"'):
        return raw[1:-1]
    if re.fullmatch(r"-?\d+", raw):
        return int(raw)
    return raw


# ---------------------------------------------------------------- Markdown subset

def esc(s: str) -> str:
    return html.escape(s, quote=True)


def slugify(text: str) -> str:
    """GitHub-style heading anchor."""
    text = re.sub(r"<[^>]+>", "", text).strip().lower()
    text = re.sub(r"[^\w\- ]", "", text)
    return text.replace(" ", "-")


INLINE_HTML = re.compile(r"&lt;(/?(?:sup|sub|kbd|br\s*/?))&gt;")


def inline(text: str, link) -> str:
    """Inline Markdown: code, links, bold, italics, and a few whitelisted tags."""
    codes: list[str] = []

    def stash(m):
        codes.append("<code>" + esc(m.group(1)) + "</code>")
        return f"\x00{len(codes) - 1}\x00"

    text = re.sub(r"`([^`]+)`", stash, text)
    text = esc(text)
    text = INLINE_HTML.sub(r"<\1>", text)
    text = re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)",
                  lambda m: f'<a href="{esc(link(html.unescape(m.group(2))))}">{m.group(1)}</a>', text)
    text = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", text)
    text = re.sub(r"(?<![\w*])\*(?![\s*])(.+?)(?<![\s*])\*(?![\w*])", r"<em>\1</em>", text)
    text = re.sub(r"(?<![\w/])_(?![\s_])(.+?)(?<![\s_])_(?![\w])", r"<em>\1</em>", text)
    if getattr(link, "lang", "en") == "fa":
        text = re.sub(r"\((pp?\.\s[^()]+)\)", lambda m: f'<span class="pref">({pages_label(m.group(1), "fa")})</span>', text)
        text = text.replace("<strong>Run it:</strong>", f'<strong>{UI["fa"]["run_marker"]}</strong>')
        text = RLM_AFTER.sub("\\1\u200f", text)
    return re.sub(r"\x00(\d+)\x00", lambda m: codes[int(m.group(1))], text)


LIST_RE = re.compile(r"^(\s*)([-*]|\d+\.)\s+")
FIGURE_RE = re.compile(r"^!\[([^\]]+)\]\(([^)\s]+)\)\s*$")
CAPTION_RE = re.compile(r"^\*(Figure [^*]*?\((?:pp?\.) [^)]+\)):(.*)\*\s*$")
TABLE_SEP = re.compile(r"^\|?\s*:?-{3,}:?\s*(\|\s*:?-{3,}:?\s*)*\|?\s*$")


def indent_of(line: str) -> int:
    return len(line) - len(line.lstrip(" "))


def is_block_start(line: str) -> bool:
    return bool(line.startswith(("```", "#", ">", "|", "![")) or LIST_RE.match(line) or line.strip() == "---")


def table_cells(line: str) -> list[str]:
    line = line.strip()
    if line.startswith("|"):
        line = line[1:]
    if line.endswith("|"):
        line = line[:-1]
    return [c.strip() for c in re.split(r"(?<!\\)\|", line)]


def md(text: str, link=lambda u: u) -> str:
    """Render the Markdown subset used by the vault's notes."""
    lines = text.split("\n")
    out: list[str] = []
    i, n = 0, len(lines)
    while i < n:
        line = lines[i]
        if not line.strip():
            i += 1
            continue
        if line.startswith("```"):
            lang = line[3:].strip()
            j = i + 1
            while j < n and not lines[j].startswith("```"):
                j += 1
            code = "\n".join(lines[i + 1:j])
            if lang == "mermaid":
                out.append(f'<figure class="diagram"><pre class="mermaid">{esc(code)}</pre></figure>')
            else:
                out.append(f'<pre class="code"><code>{esc(code)}</code></pre>')
            i = j + 1
            continue
        m = re.match(r"(#{1,6})\s+(.*)", line)
        if m:
            level, title = len(m.group(1)), m.group(2).strip()
            out.append(f'<h{level} id="{slugify(title)}">{inline(title, link)}</h{level}>')
            i += 1
            continue
        m = FIGURE_RE.match(line)
        if m:  # a book figure: the image line, then its italic caption line
            alt, src = m.group(1), link(m.group(2))
            j = i + 1
            while j < n and not lines[j].strip():
                j += 1
            cap = ""
            c = CAPTION_RE.match(lines[j]) if j < n else None
            if c:
                label = c.group(1)
                if getattr(link, "lang", "en") == "fa":
                    label = re.sub(r"^Figure ([\w.-]+)", lambda f: UI["fa"]["figure"] + " " + num(f.group(1), "fa"), label)
                cap = (f'<figcaption><span class="fig-label">{inline(label, link)}:</span> '
                       f'{inline(c.group(2).strip(), link)}</figcaption>')
                i = j
            out.append(f'<figure class="book-fig"><a href="{esc(src)}" title="{getattr(link, "ui", UI["en"])["fig_open"]}">'
                       f'<img src="{esc(src)}" alt="{esc(alt)}" loading="lazy"></a>{cap}</figure>')
            i += 1
            continue
        if line.startswith("|") and i + 1 < n and TABLE_SEP.match(lines[i + 1]):
            head = table_cells(line)
            rows = []
            j = i + 2
            while j < n and lines[j].startswith("|"):
                rows.append(table_cells(lines[j]))
                j += 1
            th = "".join(f"<th>{inline(c, link)}</th>" for c in head)
            body = "".join("<tr>" + "".join(f"<td>{inline(c, link)}</td>" for c in r) + "</tr>" for r in rows)
            out.append(f'<div class="table-wrap"><table class="data"><thead><tr>{th}</tr></thead><tbody>{body}</tbody></table></div>')
            i = j
            continue
        if line.startswith(">"):
            j = i
            quoted = []
            while j < n and lines[j].startswith(">"):
                quoted.append(re.sub(r"^> ?", "", lines[j]))
                j += 1
            if quoted and quoted[0].startswith("**In practice:**"):
                out.append(practice_callout("\n".join(quoted), link, getattr(link, "ui", UI["en"])))
                i = j
                continue
            inner = md("\n".join(quoted), link)
            cls = "callout vault" if quoted and quoted[0].startswith("**Vault note:**") else "callout"
            out.append(f'<div class="{cls}">{inner}</div>')
            i = j
            continue
        if LIST_RE.match(line):
            html_list, i = parse_list(lines, i, link)
            out.append(html_list)
            continue
        if line.strip() == "---":
            out.append("<hr>")
            i += 1
            continue
        para = [line.strip()]
        i += 1
        while i < n and lines[i].strip() and not is_block_start(lines[i]):
            para.append(lines[i].strip())
            i += 1
        out.append(f"<p>{inline(' '.join(para), link)}</p>")
    return "\n".join(out)


def practice_callout(text: str, link, t=UI["en"]) -> str:
    """'> **In practice:** …' ties a section to the reference stack (practice/reference-stack.md); an optional
    '**Your turn:** question' + '*Answer:* …' inside it becomes a reveal card."""
    head, _, turn = text.removeprefix("**In practice:**").partition("**Your turn:**")
    html = md(head.strip(), link)
    if turn:
        q, _, a = turn.partition("*Answer:*")
        html += (f'<details class="open-q turn"><summary><span class="qn" aria-hidden="true">?</span>'
                 f'<span><span class="turn-label">{t["your_turn"]}</span>{inline(" ".join(q.split()), link)}</span>'
                 f'<span class="reveal">{t["show_answer"]}</span></summary><div class="answer">{md(a.strip(), link)}</div></details>')
    return f'<div class="callout practice">{html}</div>'


def parse_list(lines: list[str], i: int, link) -> tuple[str, int]:
    first = LIST_RE.match(lines[i])
    base = len(first.group(1))
    ordered = first.group(2)[0].isdigit()
    items: list[list[str]] = []
    n = len(lines)
    width = 0
    while i < n:
        line = lines[i]
        m = LIST_RE.match(line)
        if m and len(m.group(1)) == base and m.group(2)[0].isdigit() == ordered:
            width = m.end()
            items.append([line[width:]])
            i += 1
            continue
        if not line.strip():
            j = i
            while j < n and not lines[j].strip():
                j += 1
            if j < n and indent_of(lines[j]) > base:
                items[-1].extend([""] * (j - i))
                i = j
                continue
            break
        if indent_of(line) > base:
            items[-1].append(line[min(width, indent_of(line)):])
            i += 1
            continue
        if not is_block_start(line):  # lazy continuation
            items[-1][-1] += " " + line.strip()
            i += 1
            continue
        break
    tag = "ol" if ordered else "ul"
    start = ""
    if ordered:
        num = int(first.group(2)[:-1])
        start = f' start="{num}"' if num != 1 else ""
    rendered = []
    for item in items:
        body = "\n".join(item)
        task = re.match(r"\[( |x)\]\s+", body)
        prefix = ""
        if task:
            prefix = f'<input type="checkbox" disabled{" checked" if task.group(1) == "x" else ""}> '
            body = body[task.end():]
        inner = md(body, link)
        if "" not in item:  # tight item: drop the first paragraph wrapper
            inner = re.sub(r"\A<p>(.*?)</p>", r"\1", inner, count=1, flags=re.S)
        rendered.append(f"<li>{prefix}{inner}</li>")
    return f"<{tag}{start}>" + "".join(rendered) + f"</{tag}>", i


# ---------------------------------------------------------------- chapter parsing

PAGES_SUFFIX = re.compile(r"\s*\((pp?\.\s*[^)]+)\)\s*$")
TRY_IT = re.compile(r"^> \*\*Try it:\*\* \[([^\]]+)\]\(((?:\.\./)?widgets/[^)]+\.html)\)\s*(?:[—:]\s*)?(.*)$")


def sections(body: str, level: int) -> list[tuple[str, str]]:
    """Split Markdown into (heading, content) at the given heading level, ignoring code fences.
    Content before the first heading is returned under the heading ''."""
    marker = "#" * level + " "
    parts: list[tuple[str, list[str]]] = [("", [])]
    fence = False
    for line in body.split("\n"):
        if line.startswith("```"):
            fence = not fence
        if not fence and line.startswith(marker):
            parts.append((line[len(marker):].strip(), []))
        else:
            parts[-1][1].append(line)
    return [(h, "\n".join(ls).strip("\n")) for h, ls in parts]


class Chapter:
    def __init__(self, book: "Book", path: Path):
        self.book = book
        self.path = path
        self.meta, body = split_front_matter(path.read_text(encoding="utf-8"))
        self.number = int(self.meta["chapter"])
        self.title = self.meta["title"]  # the book's own chapter title
        self.display_title = self.meta.get("translated_title") or self.title
        self.pages = self.meta.get("pages") or ""
        self.source_url = self.meta.get("source_url") or ""  # a web post's own address
        self.html_name = path.stem + ".html"
        self.lang = self.meta.get("lang") or "en"
        self.kind = self.meta.get("kind") or "book"  # "book" or "articles" (a web post series)
        self.t = UI[self.lang]

        def link(url: str) -> str:
            return self.rewrite(url)
        link.ui, link.lang = self.t, self.lang  # md() reads these to label callouts and quizzes
        self.link = link
        self.h2 = {H2_ALIASES.get(h, h): c for h, c in sections(body, 2) if h}
        self.widgets = [(m.group(1), m.group(2), m.group(3))
                        for m in (TRY_IT.match(l) for l in body.split("\n")) if m]

    @property
    def summary(self) -> str:
        return self.h2.get("Summary", "").strip()

    def blurb(self) -> str:
        text = re.sub(r"\*\*|\*|`", "", self.summary)
        sentences = re.split(r"(?<=[.?!؟])\s+", text)
        blurb = sentences[0]
        if blurb.endswith(("?", "؟")) and len(sentences) > 1:
            blurb += " " + sentences[1]
        if len(blurb) > 190:
            blurb = blurb[:190].rsplit(" ", 1)[0].rstrip(",;:—–،؛ ") + "…"
        return blurb

    def rewrite(self, url: str) -> str:
        """Rewrite a link written for GitHub (Markdown) into one for the lesson (HTML)."""
        if re.match(r"^[a-z]+:", url) or url.startswith("#"):
            return url
        path, _, frag = url.partition("#")
        if path == "../README.md":
            path = "../index.html"
        elif re.fullmatch(r"\d\d-[a-z0-9-]+\.md", path):
            path = path[:-3] + ".html"
        return path + ("#" + frag if frag else "")


class Book:
    def __init__(self, folder: Path):
        self.folder = folder
        self.slug = folder.name
        self.meta, self.body = split_front_matter((folder / "README.md").read_text(encoding="utf-8"))
        self.lang = self.meta.get("lang") or "en"
        self.kind = self.meta.get("kind") or "book"  # "book" or "articles" (a web post series)
        self.h2 = {BOOK_H2_ALIASES.get(h, h): c for h, c in sections(self.body, 2) if h}
        self.h2_name = {BOOK_H2_ALIASES.get(h, h): h for h, c in sections(self.body, 2) if h}  # as written
        self.chapters = [Chapter(self, p) for p in sorted((folder / "chapters").glob("[0-9][0-9]-*.md"))]
        self.short = self.meta.get("short_title") or self.meta["title"]
        fw = folder / "framework.md"
        self.framework = Framework(self, fw) if fw.exists() else None

    @property
    def full_title(self) -> str:
        ed = self.meta.get("edition")
        return f"{self.meta['title']}, {ed} Edition" if ed and self.kind != "articles" else self.meta["title"]

    def widget_pages(self) -> list[dict]:
        found = []
        for p in sorted((self.folder / "widgets").glob("*.html")):
            text = p.read_text(encoding="utf-8")
            title = re.search(r'<h1>(.*?)</h1>', text, re.S)
            desc = re.search(r'<meta name="description" content="([^"]*)"', text)
            found.append({"file": p.name, "chapter": int(p.name[:2]),
                          "title": html.unescape(title.group(1)) if title else p.stem,
                          "desc": re.sub(r"\s*(Illustrates .*|برای فصل[^.]*\.)$", "", html.unescape(desc.group(1))) if desc else "",
                          "lang": "fa" if re.search(r'<html lang="fa"', text) else "en"})
        return found

    def labs(self) -> list[dict]:
        found = []
        for readme in sorted((self.folder / "lab").glob("*/README.md")):
            text = readme.read_text(encoding="utf-8")
            title = re.search(r"^# (.+)$", text, re.M)
            para = re.search(r"^# .+?\n\n(.+?)\n\n", text, re.S)
            cmd = re.search(r"## (?:Run|اجرا)\n.*?```(?:sh|bash)\n(.+?)\n```", text, re.S)
            found.append({"dir": readme.parent.name, "chapter": int(readme.parent.name[:2]),
                          "title": title.group(1) if title else readme.parent.name,
                          "desc": re.sub(r"\s+", " ", para.group(1)) if para else "",
                          "cmd": cmd.group(1).strip() if cmd else ""})
        return found


class Framework:
    """A book's own analytical framework (`framework.md` beside its README): the vault's synthesis
    across chapters, laid out as a slide deck. Each `##` section is a slide; `###` subsections split it."""

    def __init__(self, book: Book, path: Path):
        self.book = book
        self.path = path
        self.meta, self.body = split_front_matter(path.read_text(encoding="utf-8"))
        self.lang = self.meta.get("lang") or book.lang
        self.t = UI[self.lang]
        self.title = self.meta.get("title") or self.t["framework"]

        def link(url: str) -> str:  # links are written for GitHub, relative to the book folder
            if re.match(r"^[a-z]+:", url) or url.startswith("#"):
                return url
            path, _, frag = url.partition("#")
            if path == "README.md":
                path = "index.html"
            elif re.fullmatch(r"chapters/\d\d-[a-z0-9-]+\.md", path):
                path = path[:-3] + ".html"
            return path + ("#" + frag if frag else "")
        link.ui, link.lang = self.t, self.lang
        self.link = link

    @property
    def map_anchor(self) -> str:
        """The slide that maps every chapter onto the framework (front matter `post_map`: its `##` heading)."""
        return slugify(self.meta.get("post_map") or "")

    @property
    def summary(self) -> str:
        intro = sections(self.body, 2)[0][1]
        return "\n".join(l for l in intro.split("\n") if not l.startswith("# ")).strip()


