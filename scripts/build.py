def render_book(book: Book) -> str:
    widgets = book.widget_pages()
    labs = book.labs()
    link = lambda u: re.sub(r"^chapters/(\d\d-[a-z0-9-]+)\.md", r"chapters/\1.html", u)
    cards = []
    for ch in book.chapters:
        tags = []
        nw = sum(1 for w in widgets if w["chapter"] == ch.number)
        nl = sum(1 for l in labs if l["chapter"] == ch.number)
        if nw:
            tags.append(f'<span class="badge accent">▶ simulation</span>')
        if nl:
            tags.append(f'<span class="badge">⌘ lab</span>')
        cards.append(f'<li><a class="card ch-card" href="chapters/{ch.html_name}">'
                     f'<span class="card-ch">Chapter {ch.number} · pp. {esc(ch.pages)}</span>'
                     f'<span class="card-title">{esc(ch.title)}</span>'
                     f'<span class="card-desc">{esc(ch.blurb())}</span>'
                     f'<span class="card-foot">{"".join(tags)}</span></a></li>')
    wcards = "".join(
        f'<li><a class="card" href="widgets/{w["file"]}"><span class="card-ch">Chapter {w["chapter"]}</span>'
        f'<span class="card-title">{esc(w["title"])}</span><span class="card-desc">{esc(w["desc"])}</span></a></li>'
        for w in widgets)
    lrows = "".join(
        f'<tr><td class="num">{l["chapter"]}</td><td><a href="lab/{l["dir"]}/README.md">{esc(l["title"])}</a></td>'
        f'<td><code>{esc(l["cmd"])}</code></td></tr>' for l in labs)
    glossary = book.h2.get("Key concepts", "")
    gtable = md(glossary, link)
    m = book.meta
    authors = " and ".join(m.get("authors") or [])
    first = book.chapters[0].html_name if book.chapters else ""
    mapping = book.h2.get("How the book fits together", "")
    body = f"""<main class="page hub" id="main">
  <section class="hero{' has-cover' if m.get('cover') else ''}">
    {f'<img class="cover" src="{esc(m["cover"])}" alt="Cover of {esc(book.full_title)}" width="240">' if m.get('cover') else ''}
    <div class="hero-text">
    <p class="eyebrow">{esc(m.get('edition', ''))} edition · {esc(str(m.get('year', '')))} · {esc(m.get('publisher', ''))}</p>
    <h1>{esc(m['title'])}</h1>
    <p class="lede">{esc(authors)}</p>
    <div class="hero-blurb">{md(book.h2.get('About', ''), link)}</div>
    <p class="row"><a class="btn primary" href="chapters/{first}">Start with chapter 1 →</a>
      <a class="btn" href="#simulations">Simulations</a><a class="btn" href="#glossary">Key concepts</a></p>
    </div>
  </section>

  <h2 id="chapters">Chapters</h2>
  <p class="section-note">Each lesson walks the chapter section by section — notes with page references, diagrams, simulations, a recap and a self-check. Use <kbd>←</kbd> <kbd>→</kbd> to move between slides.</p>
  <ul class="cards">{''.join(cards)}</ul>

  <h2 id="map">How the book fits together</h2>
  <div class="panel">{md(mapping, link)}</div>

  <h2 id="simulations">Simulations</h2>
  <p class="section-note">Interactive models of the mechanisms the book describes. They are embedded in the lessons too; implementations are the vault’s own.</p>
  <ul class="cards">{wcards}</ul>

  <h2 id="lab">Lab experiments</h2>
  <p class="section-note">Deterministic Python (standard library only). Run each from its folder; the README lists the expected output.</p>
  <div class="table-wrap panel"><table class="data"><thead><tr><th class="num">Ch.</th><th>Experiment</th><th>Command</th></tr></thead><tbody>{lrows}</tbody></table></div>

{f'''  <h2 id="companions">Companion resources</h2>
  <div class="panel">{md(book.h2["Companion resources"], link)}</div>

''' if book.h2.get("Companion resources") else ""}  <h2 id="glossary">Key concepts</h2>
  <div class="glossary">
    <label class="search"><span class="sr-only">Filter concepts</span><input type="search" placeholder="Filter concepts…" data-filter="#glossary-table tbody tr"></label>
    <div id="glossary-table">{gtable}</div>
  </div>

  <p class="footer">Notes restate the book with printed page references; anything else is labelled as the vault’s own. Source and fidelity notes: <a href="README.md">README.md</a>.</p>
</main>"""
    return page(title=book.full_title, description=f"Interactive lessons, simulations and experiments for {book.full_title}.",
                root="../../", crumbs=[("Library", "../../index.html"), (book.short, None)],
                body=body, src=f"books/{book.slug}/README.md", body_class="hub-page", mermaid=bool(mapping))


