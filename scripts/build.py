def render_book(book: Book) -> str:
    widgets = book.widget_pages()
    labs = book.labs()
    lang, h = book.lang, HUB[book.lang]
    fa = lang == "fa"

    def link(u: str) -> str:
        u = re.sub(r"^framework\.md(?=$|#)", "framework.html", u)
        return re.sub(r"^chapters/(\d\d-[a-z0-9-]+)\.md", r"chapters/\1.html", u)
    link.lang, link.ui = lang, UI[lang]

    def attr(text_lang: str) -> str:  # a Persian piece of text on an English page, or vice versa
        if text_lang == lang:
            return ""
        return RTL_ATTR if text_lang == "fa" else ' lang="en" dir="ltr"'

    # An `articles` source has posts, not chapters, and its posts carry no page numbers.
    clabel = UI[lang]["post" if book.kind == "articles" else "chapter"]
    cards = []
