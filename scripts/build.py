def slide(sid: str, title: str, inner: str, *, eyebrow: str = "", pages: str = "",
          kind: str = "", nav: str | None = None) -> dict:
    return {"id": sid, "title": title, "nav": nav or title, "kind": kind,
            "html": inner, "eyebrow": eyebrow, "pages": pages}


def quiz_html(text: str, link, t=UI["en"]) -> str:
    """'Check yourself': numbered questions; options as task items mark the answer;
    '*Answer:*' paragraphs explain. Questions without options become reveal cards."""
    blocks = re.split(r"(?m)^(?=\d+\.\s)", text.strip())
    out = []
    if blocks and not re.match(r"\d+\.\s", blocks[0]):
        out.append(f'<div class="quiz-note">{md(blocks.pop(0), link)}</div>')
    for qi, block in enumerate(b for b in blocks if b.strip()):
        q = re.match(r"\d+\.\s+(.*)", block).group(1).strip()
        q = re.sub(r"^\*\*(.*)\*\*$", r"\1", q)
        options = re.findall(r"(?m)^\s+- \[( |x)\] (.+)$", block)
        answer = re.search(r"\*Answer:\*\s*(.+)", block, re.S)
        answer_html = md(re.sub(r"(?m)^\s+", "", answer.group(1).strip()), link) if answer else ""
        if options:
            correct = [k for k, (mark, _) in enumerate(options) if mark == "x"]
            opts = "".join(
                f'<label><input type="radio" name="q{qi}" value="{k}"><span>{inline(o, link)}</span></label>'
                for k, (_, o) in enumerate(options))
            out.append(f'<fieldset class="mcq" data-answer="{correct[0] if correct else -1}">'
                       f'<legend><span class="qn">{num(qi + 1, getattr(link, "lang", "en"))}</span>{inline(q, link)}</legend>{opts}'
                       f'<div class="verdict" aria-live="polite" hidden><p class="verdict-head"></p>{answer_html}</div></fieldset>')
        else:
            out.append(f'<details class="open-q"><summary><span class="qn">{num(qi + 1, getattr(link, "lang", "en"))}</span>'
                       f'<span>{inline(q, link)}</span><span class="reveal">{t["show_answer"]}</span></summary>'
                       f'<div class="answer">{answer_html}</div></details>')
    return '<div class="quiz-list">' + "\n".join(out) + "</div>"


# The sidebar lists sections by name only: no page reference, no book section number
# ("5.3.1", "۵.۳.۴ و ۵.۳.۵", "Topic 24.", "موضوع ۲۴."); the slide itself keeps both.
_NUM = r"[0-9۰-۹]+(?:\.[0-9۰-۹]+)+\.?|[0-9۰-۹]+\."
SECTION_NO = re.compile(rf"^(?:(?:Topic|موضوع)\s+[0-9۰-۹]+\.?|(?:{_NUM})(?:\s*(?:و|and|&|,|،)\s*(?:{_NUM}))*)\s+(?=\S)")


def nav_label(title: str) -> str:
    return SECTION_NO.sub("", strip_pages(title)[0]).strip()


def strip_pages(title: str) -> tuple[str, str]:
    m = PAGES_SUFFIX.search(title)
    return (title[:m.start()], m.group(1)) if m else (title, "")


def add_content_slides(slides: list[dict], sid: str, title: str, text: str, eyebrow: str, *,
                       link, t: dict, lang: str, wpages: dict) -> None:
    """One slide for a section's prose, then one per `> **Try it:**` widget it embeds."""
    title, pages = strip_pages(title)
    kept, widgets = [], []
    for line in text.split("\n"):
        m = TRY_IT.match(line)
        (widgets.append(m) if m else kept.append(line))
    body = "\n".join(kept).strip()
    if body:
        slides.append(slide(sid, title, md(body, link), eyebrow=eyebrow, pages=pages_label(pages, lang),
                            nav=nav_label(title)))
    for m in widgets:
        file = m.group(2).split("/")[-1]
        w = wpages.get(file, {"title": m.group(1)})
        inner = \
            f'<div class="widget-frame"><iframe data-src="{esc(m.group(2))}#embed" title="{esc(w["title"])}"></iframe></div>' \
            f'<p class="widget-open"><a href="{esc(m.group(2))}">{t["open_full"]}</a> · {t["sim_note"]}</p>'
        slides.append(slide(f"try-{file[:-5]}", m.group(1), inner, eyebrow=t["try_it"], kind="widget",
                            nav="▶ " + m.group(1)))


def unique_ids(slides: list[dict]) -> list[dict]:
    seen: dict[str, int] = {}
    for s in slides:
        k = seen.get(s["id"], 0)
        seen[s["id"]] = k + 1
        if k:
            s["id"] += f"-{k + 1}"
    return slides


def lesson_slides(ch: Chapter) -> list[dict]:
    book, link, t = ch.book, ch.link, ch.t
    slides: list[dict] = []
    wpages = {w["file"]: w for w in book.widget_pages()}

    def content_slides(sid: str, title: str, text: str, eyebrow: str):
        add_content_slides(slides, sid, title, text, eyebrow, link=link, t=t, lang=ch.lang, wpages=wpages)

    # Cover: summary + the book's own outline.
    outline = ch.h2.get("Section outline", "")
    outline = re.sub(r"^\*(?:From the book|از فهرست مطالب).*\*\s*$", "", outline, flags=re.M).strip()
    cover = (f'<div class="cover-summary">{md(ch.summary, link)}</div>'
             f'<details class="outline"><summary>{t["outline"]}</summary>'
             f'{md(outline, link)}</details>')
    slides.append(slide("overview", ch.display_title, cover, eyebrow=t["post" if book.kind == "articles" else "chapter"].format(n=num(ch.number, ch.lang)),
                        pages=pages_label(f"pp. {ch.pages}", ch.lang) if ch.pages else "", kind="cover",
                        nav=t["overview"]))

    for h3, text in sections(ch.h2.get("Notes", ""), 3):
        if not h3:
            if text.strip():  # the chapter's own introduction, before its first section
                content_slides("introduction", t["post_text"] if book.kind == "articles" else t["introduction"], text, t["from_post"] if book.kind == "articles" else t["from_book"])
            continue
        subs = sections(text, 4)
        intro = subs[0][1]
        parent = strip_pages(h3)[0]
        if len(subs) == 1:
            content_slides(slugify(parent), h3, intro, t["from_book"])
            continue
        if intro.strip():
            content_slides(slugify(parent), h3, intro, t["from_book"])
        for h4, sub in subs[1:]:
            content_slides(slugify(strip_pages(h4)[0]), h4, sub, parent)

    if ch.h2.get("Trade-offs at a glance"):
        slides.append(slide("trade-offs", t["tradeoffs"], md(ch.h2["Trade-offs at a glance"], link),
                            eyebrow=t["recap"]))
    if ch.h2.get("Key takeaways"):
        slides.append(slide("takeaways", t["takeaways"], md(ch.h2["Key takeaways"], link), eyebrow=t["recap"],
                            kind="takeaways"))
    if ch.h2.get("Check yourself"):
        slides.append(slide("check", t["check"], quiz_html(ch.h2["Check yourself"], link, t),
                            eyebrow=t["practice"], kind="quiz"))
    if ch.h2.get("Beyond the book"):
        slides.append(slide("beyond", t["beyond"],
                            f'<p class="vault-flag">{t["vault_flag"]}</p>' +
                            md(ch.h2["Beyond the book"], link), eyebrow=t["supplement"], kind="beyond"))

    # Keep going: experiments, related chapters, next chapter.
    labs = [l for l in book.labs() if l["chapter"] == ch.number]
    parts = []
    for l in labs:
        parts.append(f'<div class="lab-card"><p class="lab-title"><a href="../lab/{l["dir"]}/README.md">{esc(l["title"])}</a></p>'
                     f'<p>{inline(l["desc"], link)}</p>'
                     f'<pre class="code"><code>cd books/{book.slug}/lab/{l["dir"]}\n{esc(l["cmd"])}</code></pre></div>')
    conn = ch.h2.get("Connections", "")
    nxt = next((c for c in book.chapters if c.number == ch.number + 1), None)
    nav = (f'<a class="btn primary" href="{nxt.html_name}">{esc(t["next_ch"].format(n=num(nxt.number, ch.lang), title=nxt.display_title))}</a>' if nxt
           else f'<a class="btn primary" href="../index.html">{t["back"]}</a>')
    fw = (f'<a class="btn" href="../framework.html#{book.framework.map_anchor}">{t["framework_link"]}</a>' if book.framework else "")
    src = (f'<a class="btn" href="{esc(ch.source_url)}" rel="noopener">{t["source"]}</a>' if ch.source_url else "")
    keep = ((f'<p class="source-link">{src}{fw}</p>' if src or fw else "") +
            (f'<h3>{t["run_it"]}</h3>{"".join(parts)}' if parts else "") +
            (f'<h3>{t["connections"]}</h3>{md(conn, link)}' if conn else "") +
            f'<p class="next-row">{nav}</p>')
    slides.append(slide("next", t["keep"], keep, eyebrow=t["next_steps"], kind="end"))
    return unique_ids(slides)


def deck(slides: list[dict], *, t: dict, lang: str, link, cover_head: str, toc_title: str, toc_foot: str) -> str:
    """The slide-deck body shared by lessons and a book's framework page."""
    toc = []
    for i, s in enumerate(slides):
        cls = f' class="toc-{s["kind"]}"' if s["kind"] else ""
        toc.append(f'<li{cls}><a href="#{s["id"]}" data-i="{i}"><span class="toc-i">{num(i + 1, lang)}</span>{esc(re.sub(r"<[^>]+>", "", s["nav"]))}</a></li>')
    sections_html = []
    for s in slides:
        if s["kind"] != "cover":
            pages = f'<span class="pages">{esc(s["pages"])}</span>' if s["pages"] else ""
            head = (f'<header class="slide-head"><p class="eyebrow">{esc(s["eyebrow"])}</p>'
                    f'<h2>{inline(s["title"], link)}</h2>{pages}</header>')
        else:
            head = cover_head.replace("{pages}", f' · {esc(s["pages"])}' if s["pages"] else "")
        kind = f' slide-{s["kind"]}' if s["kind"] else ""
        sections_html.append(
            f'<section class="slide{kind}" id="{s["id"]}" aria-label="{esc(re.sub(r"<[^>]+>", "", s["title"]))}">'
            f'<div class="slide-inner">{head}<div class="slide-body">{s["html"]}</div></div></section>')
    return f"""<div class="progress" aria-hidden="true"><div class="progress-bar"></div></div>
<div class="lesson-shell">
  <nav class="toc" id="toc" aria-label="{t["toc_aria"]}">
    <p class="toc-title">{esc(toc_title)}</p>
    <ol>{''.join(toc)}</ol>
    <p class="toc-foot">{toc_foot}</p>
  </nav>
  <main class="deck" id="main" tabindex="-1">
{chr(10).join(sections_html)}
  </main>
</div>
<nav class="deck-nav" aria-label="{t["nav_aria"]}">
  <button class="btn" type="button" data-go="-1" aria-label="{t["prev_aria"]}"><span class="arrow">←</span> <span>{t["prev"]}</span></button>
  <button class="btn toc-toggle" type="button" aria-controls="toc" aria-expanded="false">{t["contents"]}</button>
  <span class="deck-count" aria-live="polite"></span>
  <button class="btn primary" type="button" data-go="1" aria-label="{t["next_aria"]}"><span>{t["next"]}</span> <span class="arrow">→</span></button>
</nav>"""


def render_lesson(ch: Chapter) -> str:
    book, t = ch.book, ch.t
    slides = lesson_slides(ch)
    cover_head = (f'<header class="slide-head"><div class="cover-num" aria-hidden="true">{num(ch.number, ch.lang)}</div>'
                  f'<p class="eyebrow">{esc(slides[0]["eyebrow"])}{{pages}}</p>'
                  f'<h1>{esc(ch.display_title)}</h1>' +
                  (f'<p class="orig-title" lang="en" dir="ltr">{esc(ch.title)}</p>' if ch.display_title != ch.title else '') +
                  f'<p class="book-line">{esc(book.full_title)}</p>' +
                  (f'<p class="source-link"><a class="btn" href="{esc(ch.source_url)}" rel="noopener">{t["source"]}</a></p>' if ch.source_url else '') +
                  '</header>')
    prev_ch = next((c for c in book.chapters if c.number == ch.number - 1), None)
    toc_foot = (f'<a href="{ch.path.name}">{t["md_source"]}</a>' +
                (f' · <a href="{prev_ch.html_name}">{t["prev_post" if book.kind == "articles" else "prev_ch"].format(n=num(prev_ch.number, ch.lang))}</a>' if prev_ch else ''))
    body = deck(slides, t=t, lang=ch.lang, link=ch.link, cover_head=cover_head,
                toc_title=t["chapter"].format(n=num(ch.number, ch.lang)), toc_foot=toc_foot)
    has_mermaid = any("pre class=\"mermaid\"" in s["html"] for s in slides)
    return page(title=f"{num(ch.number, ch.lang)}. {ch.display_title} · {book.short}",
                description=ch.blurb(), root="../../../",
                crumbs=[(t["library"], "../../../index.html"), (book.short, "../index.html"),
                        (t["chapter"].format(n=num(ch.number, ch.lang)), None)],
                body=body, src=f"books/{book.slug}/chapters/{ch.path.name}", body_class="lesson", mermaid=has_mermaid,
                lang=ch.lang)


