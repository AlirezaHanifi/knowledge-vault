def library_card(b: "Book") -> str:
    m, cover = b.meta, b.meta.get("cover")
    counts = ((len(b.chapters), LIB["units"][b.kind]), (len(b.widget_pages()), LIB["sims"]), (len(b.labs()), LIB["labs"]))
    stats = "".join(f'<span class="book-stat"><b>{num(n, "fa")}</b> {label}</span>' for n, label in counts if n)
    if b.kind == "articles":
        facts = [LIB["series"], num(m.get("year") or "", "fa"), re.sub(r"\s*\(.*\)", "", m.get("publisher") or "")]
    else:
        ed = m.get("edition") or ""
        facts = [LIB["edition"].format(ed=FA_ORDINALS.get(ed, ed)) if ed else "", num(m.get("year") or "", "fa"),
                 m.get("publisher") or "", LIB["pages"].format(n=num(m["pages"], "fa")) if m.get("pages") else ""]
    return (f'<li><a class="card book-card" href="books/{b.slug}/index.html">'
            + (f'<img class="cover" src="books/{b.slug}/{esc(cover)}" alt="" width="120">' if cover else "") +
            '<span class="book-info">'
            f'<span class="card-ch" lang="en">{esc(" · ".join(m.get("authors") or []))}</span>'
            f'<span class="card-title" lang="en">{esc(m["title"])}</span>'
            f'<span class="book-facts">{esc(" · ".join(f for f in facts if f))}</span>'
            '</span>'
            f'<span class="book-stats">{stats}</span></a></li>')


def render_library(books: list[Book]) -> str:
    groups = ""
    for kind, heading in LIB["groups"].items():
        chosen = [b for b in books if b.kind == kind]
        if not chosen:
            continue
        cards = "".join(library_card(b) for b in chosen)
        groups += (f'\n  <h2 id="{slugify(heading)}">{heading}</h2>'
                   f'\n  <p class="section-note">{LIB["notes"][kind]}</p>'
                   f'\n  <ul class="cards library">{cards}</ul>')
    body = f"""<main class="page hub" id="main">
  <section class="hero">
    <p class="eyebrow" lang="en">Knowledge Vault</p>
    <h1>{LIB["h1"]}</h1>
    <p class="lede">{LIB["lede"]}</p>
  </section>{groups}
  <p class="footer">{LIB["footer"]}</p>
</main>"""
    return page(title="Knowledge Vault", description=LIB["desc"], root="", lang="fa",
                crumbs=[(UI["fa"]["library"], None)], body=body, src="books/*/README.md", body_class="hub-page")


# ---------------------------------------------------------------- driver

def outputs() -> dict[Path, str]:
    books = [Book(p.parent) for p in sorted(BOOKS.glob("*/README.md"))]
    out: dict[Path, str] = {ROOT / "index.html": render_library(books)}
    for b in books:
        out[b.folder / "index.html"] = render_book(b)
        if b.framework:
            out[b.folder / "framework.html"] = render_framework(b.framework)
        for ch in b.chapters:
            out[ch.path.with_suffix(".html")] = render_lesson(ch)
    return out


def main() -> int:
    check = "--check" in sys.argv[1:]
    stale = []
    for path, text in outputs().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != text:
            stale.append(path.relative_to(ROOT))
            if not check:
                path.write_text(text, encoding="utf-8")
    if check:
        for p in stale:
            print(f"stale: {p}")
        if stale:
            print("Run: python3 scripts/build.py")
        return 1 if stale else 0
    print(f"Built {len(stale)} changed page(s).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
