def render_framework(fw: Framework) -> str:
    book, t, link, lang = fw.book, fw.t, fw.link, fw.lang
    wpages = {w["file"]: w for w in book.widget_pages()}
    slides = [slide("overview", fw.title, f'<p class="vault-flag">{t["framework_flag"]}</p>'
                    f'<div class="cover-summary">{md(fw.summary, link)}</div>',
                    eyebrow=t["framework_eyebrow"], kind="cover", nav=t["overview"])]
    for h2, text in sections(fw.body, 2):
        if not h2:
            continue
        subs = sections(text, 3)
        if subs[0][1].strip() or len(subs) == 1:
            add_content_slides(slides, slugify(h2), h2, subs[0][1], t["framework"], link=link, t=t, lang=lang, wpages=wpages)
        for h3, sub in subs[1:]:
            add_content_slides(slides, slugify(h3), h3, sub, h2, link=link, t=t, lang=lang, wpages=wpages)
    first = book.chapters[0].html_name if book.chapters else ""
    slides.append(slide("next", t["keep"], f'<p class="next-row"><a class="btn primary" href="chapters/{first}">'
                        f'{esc(HUB[lang]["start"])}</a> <a class="btn" href="index.html">{t["back"]}</a></p>',
                        eyebrow=t["next_steps"], kind="end"))
    unique_ids(slides)
    cover_head = (f'<header class="slide-head"><p class="eyebrow">{esc(t["framework_eyebrow"])}</p>'
                  f'<h1>{esc(fw.title)}</h1><p class="book-line">{esc(book.full_title)}</p></header>')
    body = deck(slides, t=t, lang=lang, link=link, cover_head=cover_head, toc_title=t["framework"],
                toc_foot=f'<a href="{fw.path.name}">{t["md_source"]}</a> · <a href="index.html">{esc(book.short)}</a>')
    return page(title=f"{fw.title} · {book.short}", description=re.sub(r"\*\*|\*|`|\[|\]\([^)]*\)", "", fw.summary.split("\n\n")[0])[:190],
                root="../../", crumbs=[(t["library"], "../../index.html"), (book.short, "index.html"), (t["framework"], None)],
                body=body, src=f"books/{book.slug}/{fw.path.name}", body_class="lesson",
                mermaid=any('pre class="mermaid"' in s["html"] for s in slides), lang=lang)


